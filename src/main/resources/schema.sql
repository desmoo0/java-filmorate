ALTER TABLE LIKES ADD CONSTRAINT FK_LIKES_FILM FOREIGN KEY (FILM_ID) REFERENCES FILM (ID) ON DELETE CASCADE;
ALTER TABLE LIKES ADD CONSTRAINT FK_LIKES_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID) ON DELETE CASCADE;
ALTER TABLE FRIENDS ADD CONSTRAINT FK_FRIENDS_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID) ON DELETE CASCADE;
